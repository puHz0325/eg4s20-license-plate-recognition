"""Generate the fixed LPR alphabet and six status glyphs, one bit per pixel."""
import hashlib
import json
from pathlib import Path
import sys

from PIL import Image, ImageDraw, ImageFont

CAR=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(CAR))
from lpr_common import CHARS


def main():
    out=CAR/'PL/data'
    source=Path('C:/Windows/Fonts/simhei.ttf')
    font=ImageFont.truetype(str(source),16)
    characters=CHARS[:65]+list('识别中已确认')+['-',' ']
    for char in '初始化相机故障存储等待无有效帧候选结果超时推理票数原始字重试IO/':
        if char not in characters: characters.append(char)
    assert len(characters)<=128
    def packed(text,width):
        return sum(characters.index(char)<<(7*i) for i,char in enumerate(text.ljust(width)))
    messages=['初始化','相机故障','存储等待','无有效帧','等待结果','候选无效','待确认','已确认','结果超时','推理故障']
    definitions=[f'`define OSD_STATE_{i} 49\'h{packed(text,7):013x}' for i,text in enumerate(messages)]
    for key,text in [('CONFIRM','确认'),('RAW','原始'),('LENGTH','字数'),('VOTES','票数'),('FAULT','故障'),('RETRIES','重试')]:
        definitions.append(f'`define OSD_LABEL_{key} 14\'h{packed(text,2):04x}')
    for key,text in [('SPACE',' '),('DASH','-'),('SLASH','/'),('I','I'),('O','O')]:
        definitions.append(f'`define OSD_GLYPH_{key} 7\'d{characters.index(text)}')
    (out/'osd_glyphs.vh').write_text('// Generated by sim/export_osd_font.py\n'+'\n'.join(definitions)+'\n')
    rows=[]
    preview=Image.new('RGB',(16*16,16*8),'#102030')
    for index,char in enumerate(characters):
        glyph=Image.new('1',(16,16))
        draw=ImageDraw.Draw(glyph)
        left,top,right,bottom=draw.textbbox((0,0),char,font=font)
        draw.text(((16-(right-left))//2-left,(16-(bottom-top))//2-top),char,font=font,fill=1)
        rows.extend(sum(int(glyph.getpixel((x,y))!=0)<<(15-x) for x in range(16)) for y in range(16))
        colored=Image.new('RGB',(16,16),'#102030');colored.paste('#ffffff',mask=glyph)
        preview.paste(colored,((index%16)*16,(index//16)*16))
    rows.extend([0]*(2048-len(rows)))
    for tile in range(4):
        (out/f'osd_font{tile}.hex').write_text(''.join(f'{row:04x}\n' for row in rows[tile*512:(tile+1)*512]))
    (out/'osd_font.json').write_text(json.dumps({'glyphs':characters,'width':16,'height':16,
        'font_source':str(source),'font_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
        'layout':'16 rows per glyph, bit15 is left; four 512x16 ROM tiles'},ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    directory=CAR.parent/'tmp/osd_validation';directory.mkdir(parents=True,exist_ok=True)
    preview.resize((1024,512),Image.Resampling.NEAREST).save(directory/'font_preview.png')
    print(f'Generated {len(characters)} glyphs in four 512x16 ROM tiles')


if __name__=='__main__': main()
